import { BLACK_DROPS, type DropSpot, WHITE_DROPS } from "./drops";

// 물방울은 모양마다 디자이너가 놓은 배치가 있다. 케이크를 다른 모양으로 바꾸면 계산으로 옮기지 않고 그 모양의 배치를 쓴다.
function drops(
  shape: CakeShapeId,
  color: "black" | "white",
  options: {
    // 이 케이크의 원래 모양에서의 자리. 주지 않으면 그 모양의 배치를 그대로 쓴다.
    own?: DropSpot[];
    // true면 다른 모양에서도 옆면의 물방울만 놓는다. 원래 옆면에만 물방울이 있는 케이크에 쓴다.
    wallOnly?: boolean;
    // 그 모양의 배치에서 뺄 물방울의 차례. 이 케이크의 글자와 겹쳐 글자의 일부처럼 보이는 것을 뺀다.
    omit?: Partial<Record<CakeShapeId, number[]>>;
    // 다른 모양의 물방울 크기에 곱할 배율. 원래 모양에서 물방울을 작게 놓은 케이크에 쓴다.
    scale?: number;
    // 그 모양의 물방울 전체를 옮길 거리. 옆면 물방울이 윗면 테두리에 걸리는 케이크에 쓴다.
    move?: Partial<Record<CakeShapeId, { x: number; y: number }>>;
  } = {},
): CakeDecorationItem[] {
  const layouts = color === "black" ? BLACK_DROPS : WHITE_DROPS;
  return CAKE_SHAPES.flatMap((one) =>
    one.id === shape
      ? (options.own ?? layouts[shape]).map((spot) => ({
          ...spot,
          only: [shape],
          // 예시의 원래 모양이 이 모양과 다를 때(다른 예시의 물방울을 빌려 쓸 때)도 이 자리에 놓이게 한다.
          at: { [shape]: { x: spot.x, y: spot.y } },
        }))
      : layouts[one.id]
          .filter(
            (spot, order) =>
              !options.omit?.[one.id]?.includes(order) &&
              (!options.wallOnly || spot.id.includes("oval")),
          )
          .map((spot) => {
            const move = options.move?.[one.id] ?? { x: 0, y: 0 };
            const x = spot.x + move.x;
            const y = spot.y + move.y;
            return {
              ...spot,
              x,
              y,
              scale:
                options.scale === undefined
                  ? spot.scale
                  : (spot.scale ?? 1) * options.scale,
              only: [one.id],
              at: { [one.id]: { x, y } },
            };
          }),
  );
}

interface RimLayout {
  // 두를 개수와 크기.
  count: number;
  scale: number;
  // 테두리에서 가운데 쪽으로 들어온 정도. 0이면 테두리 위, 1이면 가운데다.
  // 프로스팅이 얹혀 윗면이 바탕보다 작은 케이크는 가로세로를 따로 주고, 고리 전체를 shift만큼 옮긴다.
  inset: number | { x: number; y: number };
  shift?: { x: number; y: number };
  // 둘레의 몇 할 지점부터 몇 할 지점까지 두를지. 테두리 점은 오른쪽(0)에서 시작해 앞(0.25), 왼쪽(0.5), 뒤(0.75) 순서로 돈다.
  // 1을 넘는 값은 한 바퀴 돈 자리다. 주지 않으면 한 바퀴를 고르게 두른다.
  from?: number;
  to?: number;
}

// 윗면 테두리를 따라 같은 간격으로 두른 장식. 테두리 크림처럼 줄 전체가 모양을 따라야 하는 장식에 쓴다.
// 낱개를 계산으로 옮기면 간격이 고르지 않고 테두리를 벗어나서, 모양마다 테두리를 따라 새로 두른다.
function rim(
  id: string,
  layouts: Partial<Record<CakeShapeId, RimLayout>>,
): CakeDecorationItem[] {
  return CAKE_SHAPES.flatMap((shape) => {
    const layout = layouts[shape.id];
    if (!layout) return [];
    const { center, outline } = CAKE_TOPS[shape.id];
    const points = [...outline, outline[0]];
    const lengths = [0];
    for (let index = 1; index < points.length; index += 1) {
      const before = points[index - 1];
      const now = points[index];
      lengths.push(
        lengths[index - 1] + Math.hypot(now.x - before.x, now.y - before.y),
      );
    }
    const total = lengths[lengths.length - 1];
    const from = layout.from ?? 0;
    const to = layout.to ?? 1;
    const closed = layout.from === undefined && layout.to === undefined;
    const steps = closed ? layout.count : layout.count - 1;
    const at = (part: number) => {
      // 시작점을 넘어 두르는 고리(0.6에서 1.2까지)도 받는다.
      const distance = (part % 1) * total;
      let index = 1;
      while (index < lengths.length - 1 && lengths[index] < distance)
        index += 1;
      const before = points[index - 1];
      const now = points[index];
      const span = lengths[index] - lengths[index - 1] || 1;
      const ratio = (distance - lengths[index - 1]) / span;
      const x = before.x + (now.x - before.x) * ratio;
      const y = before.y + (now.y - before.y) * ratio;
      const inset =
        typeof layout.inset === "number"
          ? { x: layout.inset, y: layout.inset }
          : layout.inset;
      const shift = layout.shift ?? { x: 0, y: 0 };
      return {
        x: Math.round((x + (center.x - x) * inset.x + shift.x) * 10) / 10,
        y: Math.round((y + (center.y - y) * inset.y + shift.y) * 10) / 10,
      };
    };
    return Array.from({ length: layout.count }, (_, order) =>
      at(from + ((to - from) * order) / Math.max(steps, 1)),
    )
      .sort((a, b) => a.y - b.y)
      .map((spot) => ({
        id,
        ...spot,
        scale: layout.scale,
        only: [shape.id],
        at: { [shape.id]: spot },
      }));
  });
}

