/**
 * 에셋 계층.
 *
 * | 계층 | 정책 |
 * | --- | --- |
 * | `hot` | 부팅 시 1회 로드 후 **해제하지 않는다.** 총량은 예산으로 상한 관리 |
 * | `warm` | STEP.1 로 후보가 좁혀진 뒤 프리페치, 세션 종료 시 참조를 끊는다 |
 * | `cold` | 필요할 때 로드. 디코딩 예산의 완충재 |
 *
 * 이 비대칭은 Lottie 와 정반대다 — 그쪽은 반드시 해제한다 (`.claude/rules/motion.md`).
 * 나중에 누군가 "일관성" 이름으로 hot 이미지를 해제하려 들 수 있어 적어 둔다.
 *
 * **어느 에셋이 어느 계층인지는 `scripts/asset-tiers.mjs` 가 정한다.** 런타임은 그 결과가
 * 박힌 매니페스트만 읽으면 되므로 규칙을 여기 두지 않는다.
 */
export type AssetTier = 'hot' | 'warm' | 'cold'
